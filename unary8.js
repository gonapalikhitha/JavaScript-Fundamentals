//unary+
console.log(+"10");
console.log(+true);
console.log(+false);
console.log(+null);

//unary negation
console.log(-10);
console.log(-"10");
console.log(-true);
console.log(-false);

//logical NOT(!)
console.log(!true);
console.log(!false);

//bitwise NOT(~)
console.log(~5);

//void
console.log(void(5+3));

